function dosyaAdi(src: string): string {
  const ad = decodeURIComponent(src.split(/[?#]/)[0].split("/").pop() ?? "");
  return ad.replace(/-[A-Za-z0-9_-]{8}(\.[a-z]+)$/i, "$1");
}

export function boyut(src?: string): { width?: number; height?: number } {
  if (!src) return {};
  const b = YOL[src.split(/[?#]/)[0]] ?? AD[dosyaAdi(src)] ?? AD[decodeURIComponent(src.split("/").pop() ?? "")];
  return b ? { width: b[0], height: b[1] } : {};
}
